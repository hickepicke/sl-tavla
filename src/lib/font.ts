export interface Glyph {
  width: number;
  /** rows[y][x] */
  rows: boolean[][];
}

const GLYPHS = new Map<string, Glyph>();
for (const [ch, def] of Object.entries(RAW)) {
  const rows = def.split(' ').map((r) => [...r].map((c) => c === '#'));
  const width = rows[0].length;
  while (rows.length < GLYPH_HEIGHT) rows.push(new Array(width).fill(false));
  GLYPHS.set(ch, { width, rows });
}

/** Look up a glyph, folding accents we don't draw (é → e) and falling back to '?'. */
export function glyph(ch: string): Glyph {
  const g = GLYPHS.get(ch);
  if (g) return g;
  const folded = ch.normalize('NFD').replace(/[̀-ͯ]/g, '');
  return GLYPHS.get(folded) ?? GLYPHS.get(folded.toUpperCase()) ?? GLYPHS.get('?')!;
}

/** Width in dots, including one dot of spacing between glyphs. */
export function measure(text: string): number {
  let w = 0;
  for (const ch of text) w += glyph(ch).width + 1;
  return Math.max(0, w - 1);
}
